//! Interface translations. Command ids, document text and file names remain stable.
//! Untranslated labels fall back to English so coverage can grow incrementally.

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Language {
    #[default]
    En,
    Fr,
    Ja,
}

impl Language {
    pub const ALL: [Self; 3] = [Self::En, Self::Fr, Self::Ja];

    pub fn name(self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Fr => "Français",
            Self::Ja => "日本語",
        }
    }

    pub fn parse(code: &str) -> Option<Self> {
        match code {
            "en" => Some(Self::En),
            "fr" => Some(Self::Fr),
            "ja" => Some(Self::Ja),
            _ => None,
        }
    }

    /// The interface language for a system locale tag such as `fr-FR`, `fr_CA.UTF-8` or `ja`.
    /// Anything without a translation falls back to English.
    pub fn from_locale(tag: &str) -> Self {
        let primary = tag.split(['-', '_', '.', '@']).next().unwrap_or_default();
        Self::parse(&primary.to_ascii_lowercase()).unwrap_or_default()
    }

    pub fn tr(self, text: &str) -> &str {
        match self {
            Self::En => text,
            Self::Fr => {
                if let Some((_, french)) = FRENCH.iter().find(|(english, _)| *english == text) {
                    french
                } else {
                    text
                }
            }
            Self::Ja => {
                if let Some((_, japanese)) = JAPANESE.iter().find(|(english, _)| *english == text) {
                    japanese
                } else {
                    text
                }
            }
        }
    }
}

